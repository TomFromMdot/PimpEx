#include "scene/ComponentDocs.hpp"

#include <format>
#include <vector>

namespace PimpEx::scene {

std::string components_markdown(const ComponentRegistry &registry) {
  std::string out = R"(# Components

An actor (GameObject) is a name plus a set of components. A component is data:
how the actor looks, how it moves, what it stores. Behaviour is added in Lua
(`<Behavior>`, docs/behaviors.md) or in `.swap` (`PROC ... FOR Component`).

```xml
<Actor name="Player" x="100" y="200" w="32" h="32" tags="hero">
  <Rect color="blue"/>
  <Collider/>
  <Health hp="5"/>                      <!-- a component from components.xml -->
  <Behavior name="topdown_move" speed="4"/>
</Actor>
```

- `Transform` and `Body` fields can be written directly on `<Actor>` (`x="10" vx="2"`).
- In `.swap` and Lua a field is `Actor.field` (shortcuts: `x`, `vx`, `rotation`...)
  or `Actor.Component.field`, e.g. `Player.Health.hp`, `Cam.Camera.zoom`.
- A missing component is added on the first `SET`.
- This file is generated by `pimpex components --markdown`. In a project with
  `components.xml` the command also lists the user components.

## User components: `components.xml`

```xml
<Components>
  <Component name="Health" doc="Hit points">
    <Field name="hp" type="number" default="3"/>
    <Field name="shield" type="bool" default="false"/>
  </Component>
</Components>
```

Field types: `number`, `integer`, `bool`, `text`, `color`.
)";

  std::string group;
  for (const auto &c : registry.all()) {
    if (c.group != group) {
      group = c.group;
      out += std::format("\n## {}\n", group == "user" ? "User components (components.xml)"
                                                     : "Built-in: " + group);
    }
    out += std::format("\n### `<{}>`\n\n{}\n\n", c.name, c.doc.empty() ? "–" : c.doc);
    if (c.fields.empty()) {
      out += "No fields.\n";
      continue;
    }
    out += "| Field | Type | Default | Description |\n|-------|------|---------|-------------|\n";
    for (const auto &f : c.fields) {
      std::string type(field_type_name(f.type));
      if (!f.choices.empty()) {
        type.clear();
        for (const auto &choice : f.choices)
          type += (type.empty() ? "" : " \\| ") + choice;
      }
      auto def = field_value_to_string(f.defaultValue);
      if (f.type == FieldType::Bool)
        def = def == "1" ? "true" : "false";
      out += std::format("| `{}` | {} | `{}` | {}{} |\n", f.name, type, def.empty() ? "\"\"" : def,
                         f.doc, f.readOnly ? " (read-only)" : "");
    }
  }
  return out;
}

} // namespace PimpEx::scene
